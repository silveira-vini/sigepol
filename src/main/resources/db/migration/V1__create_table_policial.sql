CREATE TABLE policial
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name              VARCHAR(100),
    cpf               VARCHAR(15),
    email             VARCHAR(100),
    nascimento        TIMESTAMP WITHOUT TIME ZONE,
    nome_mae          VARCHAR(100),
    nome_pai          VARCHAR(100),
    patente           VARCHAR(10),
    nome_de_guerra    VARCHAR(30),
    lotacao           VARCHAR(30),
    matricula         INTEGER,
    data_incorporacao TIMESTAMP WITHOUT TIME ZONE,
    ativo             BOOLEAN                                 NOT NULL,
    grau              VARCHAR(30),
    curso             VARCHAR(30),
    concluido         BOOLEAN,
    ano_conclusao     INTEGER,
    logradouro        VARCHAR(40),
    numero            VARCHAR(10),
    complemento       VARCHAR(40),
    bairro            VARCHAR(40),
    cidade            VARCHAR(40),
    uf                VARCHAR(2),
    cep               VARCHAR(10),
    CONSTRAINT pk_policial PRIMARY KEY (id)
);